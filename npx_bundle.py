"""npx-bundle: build the tree this repo publishes on its `npx` branch.

    python3 npx_bundle.py build <out-dir>

The third-party skills CLI (`npx skills add`) installs a skill by
copying its folder alone out of a clone it then deletes (ADR-0120).
Most skills here read the plugin root: the pipeline protocol, CONTEXT.md,
factory/ and the root tools. So the branch adds one more skill,
`idea-to-prod-runtime`, holding those files at their root-relative
paths, and rewrites every skill's plugin-root path to name that sibling
folder, which installs beside it. main never holds the copy; the
npx-branch workflow builds and force-pushes it on each release.

Build refuses a non-empty output directory, then checks its own
output: every rewritten path must resolve inside the runtime, no path
may still climb past the installed skill folders, and no file may be
one the CLI never copies. Problems are `npx-bundle:` strings; the exit
code is 1 with any, 0 clean, 2 on bad usage. Stdlib only, root-only:
no payload tool imports it.
"""
import json
import re
import shutil
import sys
from pathlib import Path

from cli import CLI_FAILURES, report, runner

RUNTIME = "idea-to-prod-runtime"
LABEL = "npx-bundle"
NOTE_HEADING = "## Installed by the skills CLI"

# What the runtime holds: every root Python tool, the root files a skill
# or tool reads, and the payload trees. Paths keep their root-relative
# shape, because the tools find their payload beside themselves.
ROOT_FILES = frozenset({"CONTEXT.md", "LICENSE", "NOTICE", "dashboard.html"})
NESTED_FILES = frozenset({".claude-plugin/plugin.json",
                          "docs/pipeline-protocol.md", "docs/standards.json"})
TREES = ("factory/", "licenses/", "output-styles/")
# The CLI's copy skips any file by this name (src/installer.ts).
CLI_DROPPED = "metadata.json"

# A run of `../` segments not glued to a longer path token on its left.
# A `/` may precede it (`<this skill's directory>/../../kb.py`).
PARENT_RUN = re.compile(r"(?<![A-Za-z0-9_.-])((?:\.\./)+)([A-Za-z0-9_.-]*)")
TWO_LEVELS = re.compile(r"two levels above this skill's base(\s+)directory")
RUNTIME_PATH = re.compile(
    rf"\.\./{re.escape(RUNTIME)}/([A-Za-z0-9_./-]*[A-Za-z0-9_/-])?")
PATH_TOKEN = re.compile(r"[A-Za-z0-9_./-]*[A-Za-z0-9_/-]")

NOTE = f"""

{NOTE_HEADING}

This copy came from this repo's `npx` branch. The plugin root these
steps name is the sibling folder `../{RUNTIME}/`, which holds the
pipeline protocol, `CONTEXT.md`, `factory/` and every root tool. Where a
step runs a tool from the plugin root or the factory repo checkout, run
`python3 <this skill's directory>/../{RUNTIME}/<tool>.py`. A stamped
repo's `tools/factory/` copy still wins wherever a step says so. Two
plugin features are absent: the `/idea-to-prod:<skill>` names (use
`/<skill>`) and the house-voice output style.
"""

RUNTIME_SKILL = """---
name: {name}
description: Support files for the idea-to-prod skills, holding the pipeline protocol, factory templates and root tools that the other skills read by path from this folder. Never invoke it, and never remove it while those skills are installed.
---

# idea-to-prod runtime

Built from idea-to-prod {version}. The skills CLI copies each skill's
folder alone, so this folder carries the plugin root the other skills
read. Its files keep their root-relative paths: `docs/pipeline-protocol.md`,
`CONTEXT.md`, `factory/`, `.claude-plugin/plugin.json` and every root
`*.py` tool. Nothing here is meant to be invoked as a skill.
"""

BRANCH_README = """# idea-to-prod, as installed by the skills CLI

Generated by `npx_bundle.py` from idea-to-prod {version} on `main`; never
edit this branch by hand. Install every skill with

    npx skills add mattbutlerengineering/skills#npx

The `{name}` skill holds the plugin root the other skills read, so
keep it installed beside them. The source, docs and Claude Code plugin
live on `main`: https://github.com/mattbutlerengineering/skills
"""


def rewrite(text, slugs):
    """TEXT with every plugin-root path renamed onto the runtime folder.
    Exactly two `../` segments not followed by a sibling skill's slug is
    a plugin-root path (skill-directory relative, as the skills write
    them); a sibling's path and any other run are left for check."""
    def move(match):
        run, head = match.group(1), match.group(2)
        if run != "../../" or head in slugs:
            return match.group(0)
        return f"../{RUNTIME}/{head}"
    moved = PARENT_RUN.sub(move, text)
    return TWO_LEVELS.sub(rf"in `../{RUNTIME}/` beside this skill's base"
                          r"\1directory", moved)


def bundled(tracked):
    """The tracked root-relative paths the runtime holds, sorted."""
    return sorted(path for path in tracked
                  if ("/" not in path
                      and (path.endswith(".py") or path in ROOT_FILES))
                  or path in NESTED_FILES or path.startswith(TREES))


def _skill_slugs(tracked):
    return sorted({path.split("/")[1] for path in tracked
                   if re.fullmatch(r"skills/[^/]+/SKILL\.md", path)})


def _copy(source, dest):
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, dest)
    shutil.copymode(source, dest)


def _version(root):
    try:
        data = json.loads((root / ".claude-plugin" / "plugin.json")
                          .read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "unversioned"
    if not isinstance(data, dict):
        return "unversioned"
    return data.get("version") or "unversioned"


def _write_skills(root, out, tracked, slugs):
    for rel in tracked:
        if not rel.startswith("skills/"):
            continue
        dest = out / rel
        if not rel.endswith(".md"):
            _copy(root / rel, dest)
            continue
        text = rewrite((root / rel).read_text(encoding="utf-8"), slugs)
        if re.fullmatch(r"skills/[^/]+/SKILL\.md", rel):
            text = text.rstrip("\n") + NOTE
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")


def _write_runtime(root, out, tracked, version):
    runtime = out / "skills" / RUNTIME
    for rel in bundled(tracked):
        _copy(root / rel, runtime / rel)
    (runtime / "SKILL.md").write_text(
        RUNTIME_SKILL.format(name=RUNTIME, version=version),
        encoding="utf-8")
    (out / "README.md").write_text(
        BRANCH_README.format(name=RUNTIME, version=version),
        encoding="utf-8")
    for name in ("LICENSE", "NOTICE"):
        if name in tracked:
            _copy(root / name, out / name)


def build(root, out, tracked):
    """Write the branch tree for ROOT's TRACKED files into OUT, then
    return check's problems for it ([] when clean)."""
    root, out = Path(root), Path(out)
    if out.exists() and any(out.iterdir()):
        return [f"{LABEL}: output directory {out} is not empty"]
    slugs = _skill_slugs(tracked)
    if RUNTIME in slugs:
        return [f"{LABEL}: skills/{RUNTIME} already exists; the runtime"
                " skill needs that name"]
    _write_skills(root, out, tracked, slugs)
    _write_runtime(root, out, tracked, _version(root))
    return check(out)


def _path_problems(rel, text, runtime, slugs):
    problems = []
    for match in RUNTIME_PATH.finditer(text):
        target = match.group(1) or ""
        if not (runtime / target).exists():
            problems.append(f"{LABEL}: {rel} names '../{RUNTIME}/{target}',"
                            " which the runtime does not hold")
    for match in PARENT_RUN.finditer(text):
        run, head = match.group(1), match.group(2)
        if run == "../" or (run == "../../" and head in slugs):
            continue
        token = PATH_TOKEN.match(text, match.start()).group(0)
        problems.append(f"{LABEL}: {rel} still names '{token}', outside"
                        " the installed skill folders")
    return problems


def check(out):
    """Problems with a built tree: a runtime path that does not resolve,
    a path still climbing past the installed skill folders, or a file the
    CLI never copies. Read off OUT alone, so a hand-edited tree is judged
    the same way."""
    skills = Path(out) / "skills"
    runtime = skills / RUNTIME
    slugs = sorted(path.name for path in skills.iterdir() if path.is_dir())
    problems = []
    for path in sorted(skills.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(out).as_posix()
        if path.name == CLI_DROPPED:
            problems.append(f"{LABEL}: {rel} is named {CLI_DROPPED}, which"
                            " the skills CLI never copies")
        if path.suffix == ".md" and runtime not in path.parents:
            problems += _path_problems(
                rel, path.read_text(encoding="utf-8"), runtime, slugs)
    return problems


def tracked_files(root, run=runner("git")):
    """ROOT's tracked paths through `git ls-files`, or a problem."""
    try:
        listing = run(["-C", str(root), "ls-files", "-z"]).stdout
    except CLI_FAILURES as err:
        return None, f"{LABEL}: git ls-files failed: {err}"
    return [path for path in listing.split("\0") if path], None


def main(argv):
    if len(argv) != 2 or argv[0] != "build":
        print(__doc__.strip())
        return 2
    root = Path(__file__).resolve().parent
    tracked, problem = tracked_files(root)
    problems = [problem] if problem else build(root, Path(argv[1]), tracked)
    return report(LABEL, problems)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
